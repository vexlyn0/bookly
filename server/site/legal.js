/** Страница по пути (/privacy, /terms) или null. Тексты собираются заново — чтобы подхватить contacts.js. */
function findLegal(pathname) {
  const page = Object.values(PAGES)
    .map((build) => build())
    .find((p) => p.path === pathname);
  return page ? { ...page, updated: UPDATED } : null;
}

