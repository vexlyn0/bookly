function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** «ИП …, ИИН …, г. Алматы» или «владелец сервиса Jazyl». */
function operatorText() {
  const parts = [CONTACTS.operator, CONTACTS.bin && `ИИН/БИН ${CONTACTS.bin}`, CONTACTS.address].filter(Boolean);
  return parts.length ? escapeHtml(parts.join(", ")) : "владелец сервиса Jazyl";
}

/** Как с нами связаться — то, что заполнено в contacts.js. */
function contactText() {
  const items = [];
  if (CONTACTS.email) items.push(`почта <a href="mailto:${escapeHtml(CONTACTS.email)}">${escapeHtml(CONTACTS.email)}</a>`);
  if (CONTACTS.whatsapp) {
    const digits = CONTACTS.whatsapp.replace(/\D/g, "");
    items.push(`WhatsApp <a href="https://wa.me/${digits}" target="_blank" rel="noopener">${escapeHtml(CONTACTS.whatsapp)}</a>`);
  }
  if (CONTACTS.telegram) {
    items.push(`Telegram <a href="https://t.me/${escapeHtml(CONTACTS.telegram)}" target="_blank" rel="noopener">@${escapeHtml(CONTACTS.telegram)}</a>`);
  }
  if (CONTACTS.instagram) {
    items.push(`Instagram <a href="https://instagram.com/${escapeHtml(CONTACTS.instagram)}" target="_blank" rel="noopener">@${escapeHtml(CONTACTS.instagram)}</a>`);
  }
  return items.length ? items.join(", ") : "контакты, указанные внизу сайта";
}

